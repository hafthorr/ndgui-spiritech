"""Fork stock window packages into ndGUI providers that use the ndGUI frame.

Run: python tools/fork_windows.py   (from the ndgui folder; re-run after client updates)

Each stock package in ROLES is copied verbatim into UI/Addons/ndgui-<slug>/, with
exactly one change to its Lua: Window.create({ ... }) gets
template = "library://notum.ndgui-lib/window.xml". Its manifest becomes a provider
manifest for the same role. If a stock file no longer matches expectations the script
stops instead of guessing.
"""
import os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ADDONS = os.path.normpath(os.path.join(HERE, "..", ".."))
STOCK = os.path.normpath(os.path.join(ADDONS, "..", "Packages"))
TEMPLATE = 'library://notum.ndgui-lib/window.xml'

# Stock folder -> (role, display name). Only window packages built on core.window.
ROLES = {
    "Actions": ("prk.actions", "Actions"),
    "AggDef": ("prk.aggdef", "Agg/Def"),
    "ChatFrame": ("prk.chat-frame", "Chat Windows"),
    "Friends": ("prk.friends", "Friends"),
    "Info": ("prk.info", "Info"),
    "Inventory": ("prk.inventory", "Inventory"),
    "Market": ("prk.market", "Market"),
    "MissionTerminal": ("prk.mission-terminal", "Mission Terminal"),
    "Missions": ("prk.missions", "Missions"),
    "NanoPrograms": ("prk.nano-programs", "Nano Programs"),
    "NpcChat": ("prk.npc-chat", "NPC Dialogue"),
    "Perks": ("prk.perks", "Perks"),
    "Pets": ("prk.pets", "Pets"),
    "Raid": ("prk.raid", "Raid"),
    "Skills": ("prk.skills", "Skills"),
    "Stats": ("prk.stats", "Stats"),
    "Trade": ("prk.trade", "Trade"),
    "Tradeskills": ("prk.tradeskills", "Tradeskills"),
    "Wear": ("prk.wear", "Wear"),
}

# Packages ndGUI owns by hand (never overwritten by this script).
HAND_MADE = {"ndgui", "ndgui-lib", "ndgui-playfield-map", "ndgui-status-bars", "ndgui-compass", "ndgui-target-panels",
             "ndgui-hotbar", "ndgui-control-center",
             "ndgui-planet-map", "ndgui-team"}

MARK = "-- ndGUI fork: generated by ndgui/tools/fork_windows.py from UI/Packages/{src}. Do not hand-edit.\n"


def slug(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def fork(src, role, title):
    sdir = os.path.join(STOCK, src)
    dest_name = "ndgui-" + slug(src)
    assert dest_name not in HAND_MADE
    ddir = os.path.join(ADDONS, dest_name)
    manifest = open(os.path.join(sdir, "package.xml"), encoding="utf-8").read()
    scripts = re.findall(r'<(Script|InteractionScript) src="([^"]+)"\s*/>', manifest)
    extra = re.sub(r'<\?xml[^>]*\?>|</?Package[^>]*>|<(Script|InteractionScript) src="[^"]+"\s*/>|<Provides[^>]*/>|\s', "", manifest)
    if extra:
        raise SystemExit(f"{src}: unexpected manifest content {extra!r}")
    if os.path.isdir(ddir):
        shutil.rmtree(ddir)
    shutil.copytree(sdir, ddir)
    creates = 0
    for fn in os.listdir(ddir):
        if not fn.endswith(".lua"):
            continue
        path = os.path.join(ddir, fn)
        code = open(path, encoding="utf-8").read()
        code = code.replace('ui.require("core.table")', 'ui.require("notum.ndgui-lib/table")')  # hideable columns (lib_table.py)
        n = code.count("Window.create({")
        if n:
            code = code.replace("Window.create({", 'Window.create({\n\ttemplate = "%s",' % TEMPLATE)
            creates += n
        open(path, "w", encoding="utf-8", newline="\n").write(MARK.format(src=src) + code)
    if creates < 1:
        raise SystemExit(f"{src}: no Window.create({{ found")
    lines = [f'<Package id="notum.{dest_name}" name="Notum Dovvetech {title}">',
             '  <Requires package="notum.ndgui-lib" />',
             f'  <Provides role="{role}" />']
    lines += [f'  <{kind} src="{name}" />' for kind, name in scripts]
    lines.append("</Package>")
    open(os.path.join(ddir, "package.xml"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    return dest_name, creates


def main():
    for src, (role, title) in ROLES.items():
        name, n = fork(src, role, title)
        print(f"{name:28s} {role:24s} frames={n}")


if __name__ == "__main__":
    main()
