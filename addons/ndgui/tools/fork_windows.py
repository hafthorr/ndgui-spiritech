# Packages ndGUI owns by hand (never overwritten by this script).
HAND_MADE = {"ndgui", "ndgui-lib", "ndgui-playfield-map", "ndgui-status-bars", "ndgui-compass", "ndgui-target-panels",
             "ndgui-hotbar", "ndgui-control-center",
             "ndgui-planet-map", "ndgui-team", "ndgui-mission-hub", "ndgui-mission-terminal", "ndgui-watch", "ndgui-intel"}

MARK = "-- ndGUI fork: generated by ndgui/tools/fork_windows.py from UI/Packages/{src}. Do not hand-edit.\n"
GRID = 'ui.require("notum.ndgui-lib/grid")  -- snap to grid while moving/resizing (ndgui-lib/lua/grid.lua)\n'
# Packages whose cells are stacked wells (ndgui_slotcell): bind via slot_cells, not icon_grid.
# Wear keeps core.icon_grid; it passes the named wear_slot_* views directly.
SLOT_CELLS = {
    "Actions", "Inventory", "Market", "NanoPrograms", "NpcChat", "Trade",
}
ICON_GRID = 'ui.require("core.icon_grid")'
SLOT_CELLS_REQ = 'ui.require("notum.ndgui-lib/slot_cells")'


def slug(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


# Live title updates also reach the docked page (ndgui-lib/lua/title.lua): Core writes the compact
# rollup_title only once. ui.text(ui.find(X, "window_title"), Y) -> Title.set(X, Y).
TITLE_FIND = re.compile(r'ui\.text\(ui\.find\(([^,()]+), "window_title"\), ')


def titles(code):
    return TITLE_FIND.sub(r'ui.require("notum.ndgui-lib/title").set(\1, ', code)


def must(text, old, new, what):
    if text.count(old) != 1:
        raise SystemExit(f"{what}: stock text changed, expected once: {old[:70]!r}")
    return text.replace(old, new)


# Inventory: remember every container per character, and search your other characters' too
# (ndgui-lib/lua/alt_items.lua). Applied to the stock files before the generic patches.
ALT_HITS = ('<TextView name="ndgui_alt_hits" value="" visible="false" color="C6A24E" font_size="11" interactive="true" '
            'size_to_text="false" text_alignment="center" min_size="Point(30,22)" max_size="Point(30,22)" v_alignment="center" '
            'layout_borders="Rect(4,0,0,0)" tooltip="" />')


def special(src, ddir):
    if src != "Inventory":
        return
    path = os.path.join(ddir, "window.xml")
    xml = open(path, encoding="utf-8").read()
    anchor = re.search(r'<TextInputView name="search_query"[^>]*/>', xml)
    if not anchor or xml.count('name="search_query"') != 1:
        raise SystemExit("Inventory/window.xml: search_query input changed")
    xml = xml.replace(anchor.group(0), anchor.group(0) + "\n      " + ALT_HITS)
    open(path, "w", encoding="utf-8", newline="\n").write(xml)
    path = os.path.join(ddir, "main.lua")
    code = open(path, encoding="utf-8").read()
    code = must(code, 'local search_query = ui.find(content, "search_query")\n',
                'local search_query = ui.find(content, "search_query")\n'
                'local AltItems = ui.require("notum.ndgui-lib/alt_items") -- ndGUI: search your other characters too\n'
                'AltItems.mount(content)\n', "Inventory/main.lua")
    code = must(code, '\tframe:set_title(title)\n\tentries, occupied, cell_of = snapshot, {}, {}\n',
                '\tframe:set_title(title)\n\tAltItems.title(title)\n\tpcall(AltItems.record, title, snapshot)\n'
                '\tentries, occupied, cell_of = snapshot, {}, {}\n', "Inventory/main.lua")
    code = must(code, '\tgame.inventory.search_edited(value)\n',
                '\tgame.inventory.search_edited(value)\n\tpcall(AltItems.search, value)\n', "Inventory/main.lua")
    open(path, "w", encoding="utf-8", newline="\n").write(code)


def fork(src, role, title):
    sdir = os.path.join(STOCK, src)
    dest_name = "ndgui-" + slug(src)
    assert dest_name not in HAND_MADE
    ddir = os.path.join(ADDONS, dest_name)
    manifest = open(os.path.join(sdir, "package.xml"), encoding="utf-8").read()
    scripts = re.findall(r'<(Script|InteractionScript) src="([^"]+)"\s*/>', manifest)
    first_script = next((name for kind, name in scripts if kind == "Script"), None)
    extra = re.sub(r'<\?xml[^>]*\?>|</?Package[^>]*>|<(Script|InteractionScript) src="[^"]+"\s*/>|<Provides[^>]*/>|\s', "", manifest)
    if extra:
        raise SystemExit(f"{src}: unexpected manifest content {extra!r}")
    if os.path.isdir(ddir):
        shutil.rmtree(ddir)
    shutil.copytree(sdir, ddir)
    special(src, ddir)
    creates = 0
    for fn in os.listdir(ddir):
        if not fn.endswith(".lua"):
            continue
        path = os.path.join(ddir, fn)
        code = open(path, encoding="utf-8").read()
        code = code.replace('ui.require("core.table")', 'ui.require("notum.ndgui-lib/table")')  # hideable columns (lib_table.py)
        if src in SLOT_CELLS:
            code = code.replace(ICON_GRID, SLOT_CELLS_REQ)
        code = titles(code)
        if fn == first_script:
            code = GRID + code
        n = code.count("Window.create({")
        if n:
            code = code.replace("Window.create({", 'Window.create({\n\ttemplate = "%s",' % TEMPLATE)
            creates += n
        if src == "Skills" and fn == first_script:
            # square_buttons wraps category Buttons; reparent the wrap with the Button.
            # Match by child identity — View userdata may not expose XML name via .name.
            old = (
                "\tvalue.button = ui.find(tree, value.name)\n"
                '\tvalue.root = ui.load("category.xml")\n'
                '\tui.add(ui.find(value.root, "button_host"), value.button)\n'
            )
            new = (
                "\t-- Next direct child is this category's wrap (chrome view + button). Do not ui.find\n"
                "\t-- through unrelated views: a missing name aborts the script and the window never fills.\n"
                "\tlocal function take_wrap(host)\n"
                "\t\tif ui.child_count(host) < 1 then\n"
                "\t\t\treturn nil, nil\n"
                "\t\tend\n"
                "\t\tlocal kid = ui.child(host, 1)\n"
                "\t\tif ui.child_count(kid) ~= 2 then\n"
                "\t\t\treturn nil, nil\n"
                "\t\tend\n"
                "\t\tlocal a, b = ui.child(kid, 1), ui.child(kid, 2)\n"
                "\t\tlocal function chrome(view)\n"
                "\t\t\tif ui.child_count(view) ~= 3 then\n"
                "\t\t\t\treturn false\n"
                "\t\t\tend\n"
                "\t\t\tfor i = 1, 3 do\n"
                "\t\t\t\tif ui.child_count(ui.child(view, i)) ~= 0 then\n"
                "\t\t\t\t\treturn false\n"
                "\t\t\t\tend\n"
                "\t\t\tend\n"
                "\t\t\treturn true\n"
                "\t\tend\n"
                "\t\tif chrome(a) then\n"
                "\t\t\treturn kid, b\n"
                "\t\tend\n"
                "\t\tif chrome(b) then\n"
                "\t\t\treturn kid, a\n"
                "\t\tend\n"
                "\t\treturn nil, nil\n"
                "\tend\n"
                "\tlocal move, button = take_wrap(tree)\n"
                "\tvalue.button = button or ui.find(tree, value.name)\n"
                "\tmove = move or value.button\n"
                '\tvalue.root = ui.load("category.xml")\n'
                '\tui.add(ui.find(value.root, "button_host"), move)\n'
            )
            if old not in code:
                raise SystemExit(f"{src}: category button reparent block changed shape")
            code = code.replace(old, new, 1)
            # ui.visible on the Button leaves the chrome wrap behind (and a wrap that
            # starts hidden never appears). Record wraps before category buttons move in.
            # One child is the 3-slice chrome and the other is not, so the priority
            # detail grid (two 3-leaf rows) is not treated as a button.
            code = must(
                code,
                'local expanded = ui.find(content, "skills_content")\n',
                'local expanded = ui.find(content, "skills_content")\n'
                "local function button_wraps(host)\n"
                "\tlocal found = {}\n"
                "\tlocal function chrome(view)\n"
                "\t\tif ui.child_count(view) ~= 3 then\n"
                "\t\t\treturn false\n"
                "\t\tend\n"
                "\t\tfor i = 1, 3 do\n"
                "\t\t\tif ui.child_count(ui.child(view, i)) ~= 0 then\n"
                "\t\t\t\treturn false\n"
                "\t\t\tend\n"
                "\t\tend\n"
                "\t\treturn true\n"
                "\tend\n"
                "\tlocal function walk(view)\n"
                "\t\tfor i = 1, ui.child_count(view) do\n"
                "\t\t\tlocal kid = ui.child(view, i)\n"
                "\t\t\tlocal n = ui.child_count(kid)\n"
                "\t\t\tif n == 2 then\n"
                "\t\t\t\tlocal a, b = ui.child(kid, 1), ui.child(kid, 2)\n"
                "\t\t\t\tif chrome(a) ~= chrome(b) and (chrome(a) or chrome(b)) then\n"
                "\t\t\t\t\tfound[#found + 1] = kid\n"
                "\t\t\t\telse\n"
                "\t\t\t\t\twalk(kid)\n"
                "\t\t\t\tend\n"
                "\t\t\telseif n > 0 then\n"
                "\t\t\t\twalk(kid)\n"
                "\t\t\tend\n"
                "\t\tend\n"
                "\tend\n"
                "\twalk(host)\n"
                "\treturn found\n"
                "end\n"
                "-- content.xml order, before category buttons are parented in.\n"
                "local priority_wrap = {}\n"
                "local wrap_names = {\n"
                '\t"suggest_ip", "set_priorities", "reset_all", "restore_priorities",\n'
                '\t"reset_skill", "use_default", "save_priorities", "cancel_priorities",\n'
                '\t"accept", "quit",\n'
                "}\n"
                "local wraps = button_wraps(expanded)\n"
                "if #wraps == #wrap_names then\n"
                "\tfor i, name in ipairs(wrap_names) do\n"
                "\t\tpriority_wrap[name] = wraps[i]\n"
                "\tend\n"
                "end\n"
                "local function show_priority_button(name, on)\n"
                "\tlocal wrap = priority_wrap[name]\n"
                "\tif wrap then\n"
                "\t\tui.visible(wrap, on)\n"
                "\tend\n"
                "\tui.visible(ui.find(expanded, name), on)\n"
                "end\n",
                "Skills/main.lua",
            )
            code = must(
                code,
                '\tfor _, name in ipairs({ "reset_all", "accept", "quit" }) do\n'
                '\t\tui.visible(ui.find(expanded, name), not priorities)\n'
                "\tend\n"
                '\tfor _, name in ipairs({ "restore_priorities", "save_priorities", "cancel_priorities" }) do\n'
                "\t\tui.visible(ui.find(expanded, name), priorities)\n"
                "\tend\n",
                '\tfor _, name in ipairs({ "reset_all", "accept", "quit" }) do\n'
                "\t\tshow_priority_button(name, not priorities)\n"
                "\tend\n"
                '\tfor _, name in ipairs({ "restore_priorities", "save_priorities", "cancel_priorities" }) do\n'
                "\t\tshow_priority_button(name, priorities)\n"
                "\tend\n",
                "Skills/main.lua",
            )
        if src == "NanoPrograms" and fn == "main.lua":
            old = (
                "local toolbar_buttons = {\n"
                "\t{ view = favorites, width = 121, row = 1 },\n"
                "\t{ view = schools[1], width = 75, row = 1 },\n"
                "\t{ view = schools[2], width = 77, row = 1 },\n"
                "\t{ view = schools[3], width = 54, row = 1 },\n"
                "\t{ view = schools[4], width = 53, row = 1 },\n"
                "\t{ view = schools[5], width = 54, row = 1 },\n"
                "}\n"
            )
            new = (
                "-- marketplace chrome wraps school Buttons; reflow must move the wrap, not the bare Button\n"
                "-- (do not key on View.name — userdata may not expose the XML name attribute)\n"
                "local function chrome_or(btn)\n"
                "\tfor i = 1, ui.child_count(first_row) do\n"
                "\t\tlocal kid = ui.child(first_row, i)\n"
                "\t\tfor j = 1, ui.child_count(kid) do\n"
                "\t\t\tif ui.child(kid, j) == btn then\n"
                "\t\t\t\treturn kid\n"
                "\t\t\tend\n"
                "\t\tend\n"
                "\tend\n"
                "\treturn btn\n"
                "end\n"
                "local toolbar_buttons = {\n"
                "\t{ view = chrome_or(favorites), width = 121, row = 1 },\n"
                "\t{ view = chrome_or(schools[1]), width = 75, row = 1 },\n"
                "\t{ view = chrome_or(schools[2]), width = 77, row = 1 },\n"
                "\t{ view = chrome_or(schools[3]), width = 54, row = 1 },\n"
                "\t{ view = chrome_or(schools[4]), width = 53, row = 1 },\n"
                "\t{ view = chrome_or(schools[5]), width = 54, row = 1 },\n"
                "}\n"
            )
            if old not in code:
                raise SystemExit(f"{src}: toolbar_buttons block changed shape")
            code = code.replace(old, new, 1)
            # Stock sizes bare 16px buttons; wrapped chrome is CONTROL_HEIGHT (22).
            code = code.replace(
                "local SEARCH_LABEL_WIDTH, SEARCH_FIELD_MINIMUM, CONTROL_HEIGHT, BUTTON_HEIGHT, BUTTON_GAP, ROW_GAP = 50, 100, 22, 16, 8, 4\n",
                "local SEARCH_LABEL_WIDTH, SEARCH_FIELD_MINIMUM, CONTROL_HEIGHT, BUTTON_GAP, ROW_GAP = 50, 100, 22, 8, 4\n",
                1,
            )
            code = code.replace(
                "\tui.size(button.view, button.width, BUTTON_HEIGHT)\n",
                "\tui.size(button.view, button.width, CONTROL_HEIGHT)\n",
                1,
            )
        if src == "Pets" and fn == first_script:
            if 'ui.require("ncu.strip")' not in code:
                raise SystemExit(f"{src}: expected ncu.strip require")
            code = code.replace(
                'ui.require("ncu.strip")',
                'ui.require("notum.ndgui-lib/ncu_strip")',
                1,
            )
            # Show buttons hides the Button only; the chrome wrap would stay as an empty frame.
            old_buttons = "    row.buttons = { row.pet_primary, row.pet_follow, row.pet_wait }\n"
            new_buttons = (
                "    row.buttons = { row.pet_primary, row.pet_follow, row.pet_wait }\n"
                "    row.chrome = {}\n"
                "    local function take_wraps(host)\n"
                "        for i = 1, ui.child_count(host) do\n"
                "            local kid = ui.child(host, i)\n"
                "            if ui.child_count(kid) == 2 then\n"
                "                local a, b = ui.child(kid, 1), ui.child(kid, 2)\n"
                "                local function chrome(view)\n"
                "                    if ui.child_count(view) ~= 3 then return false end\n"
                "                    for n = 1, 3 do\n"
                "                        if ui.child_count(ui.child(view, n)) ~= 0 then return false end\n"
                "                    end\n"
                "                    return true\n"
                "                end\n"
                "                if chrome(a) or chrome(b) then\n"
                "                    row.chrome[#row.chrome + 1] = kid\n"
                "                end\n"
                "            elseif ui.child_count(kid) > 0 then\n"
                "                take_wraps(kid)\n"
                "            end\n"
                "        end\n"
                "    end\n"
                "    take_wraps(root)\n"
            )
            if old_buttons not in code:
                raise SystemExit(f"{src}: pet button list changed shape")
            code = code.replace(old_buttons, new_buttons, 1)
            old_vis = (
                "        for _, button in ipairs(row.buttons) do\n"
                "            ui.visible(button, show_buttons)\n"
                "        end\n"
            )
            new_vis = (
                "        for index, button in ipairs(row.buttons) do\n"
                "            ui.visible(button, show_buttons)\n"
                "            if row.chrome[index] then\n"
                "                ui.visible(row.chrome[index], show_buttons)\n"
                "            end\n"
                "        end\n"
            )
            if old_vis not in code:
                raise SystemExit(f"{src}: pet button visibility changed shape")
            code = code.replace(old_vis, new_vis, 1)
        if src == "Market" and fn == "main.lua":
            # ui.visible on these Buttons hides the label and leaves the frame. Confirm
            # and Keep start hidden, and the visibility hook never sees that frame:
            # ui.find from inside the frame does not return the button. Record the
            # frames under the order panel, in content.xml order, and show both.
            code = must(
                code,
                "local function view(name)\n"
                "\treturn ui.find(content, name)\n"
                "end\n",
                "local function view(name)\n"
                "\treturn ui.find(content, name)\n"
                "end\n"
                "local show_order_button = ui.require(\"notum.ndgui-lib/button\").sync_named(content, view(\"order_selection\"), {\n"
                "\t\"collect_order\", \"cancel_order\", \"confirm_cancel\", \"keep_order\",\n"
                "\t\"order_details_button\", \"order_depth_button\", \"reprice_order\",\n"
                "})\n",
                "Market/main.lua",
            )
            for old, new in (
                (
                    "\tui.visible(view(\"confirm_cancel\"), false)\n"
                    "\tui.visible(view(\"keep_order\"), false)\n"
                    "\tui.visible(view(\"cancel_order\"), true)\n",
                    "\tshow_order_button(\"confirm_cancel\", false)\n"
                    "\tshow_order_button(\"keep_order\", false)\n"
                    "\tshow_order_button(\"cancel_order\", true)\n",
                ),
                (
                    "\tui.visible(view(\"cancel_order\"), false)\n"
                    "\tui.visible(view(\"confirm_cancel\"), true)\n"
                    "\tui.visible(view(\"keep_order\"), true)\n",
                    "\tshow_order_button(\"cancel_order\", false)\n"
                    "\tshow_order_button(\"confirm_cancel\", true)\n"
                    "\tshow_order_button(\"keep_order\", true)\n",
                ),
                (
                    "\tui.visible(view(\"cancel_order\"), true)\n"
                    "\tui.visible(view(\"confirm_cancel\"), false)\n"
                    "\tui.visible(view(\"keep_order\"), false)\n",
                    "\tshow_order_button(\"cancel_order\", true)\n"
                    "\tshow_order_button(\"confirm_cancel\", false)\n"
                    "\tshow_order_button(\"keep_order\", false)\n",
                ),
            ):
                code = must(code, old, new, "Market/main.lua")
            code = must(
                code,
                "\t\tui.visible(view(\"cancel_order\"), true)\n"
                "\t\tui.visible(view(\"confirm_cancel\"), false)\n"
                "\t\tui.visible(view(\"keep_order\"), false)\n",
                "\t\tshow_order_button(\"cancel_order\", true)\n"
                "\t\tshow_order_button(\"confirm_cancel\", false)\n"
                "\t\tshow_order_button(\"keep_order\", false)\n",
                "Market/main.lua",
            )
            open(os.path.join(ddir, "pet_ncu_slot.xml"), "w", encoding="utf-8", newline="\n").write(
                '<?xml version="1.0" encoding="utf-8"?>\n<root>\n'
                '  <View name="ndgui_slotcell" view_layout="stacked" '
                'min_size="Point(26,18)" max_size="Point(26,18)">\n'
                '    <BitmapView name="ndgui_slot_back" interactive="false" '
                'image="library://notum.ndgui-lib/slots/open_46x30.png" '
                'min_size="Point(26,18)" max_size="Point(26,18)" />\n'
                '    <ItemSlotView name="ndgui_slot" min_size="Point(26,18)" max_size="Point(26,18)" '
                'slot_gfx="" icon_inset="4" icon_inset_y="5" icon_fit="cover" overlay_inset="3" />\n'
                "  </View>\n</root>\n"
            )
        open(path, "w", encoding="utf-8", newline="\n").write(MARK.format(src=src) + code)
    if creates < 1:
        raise SystemExit(f"{src}: no Window.create({{ found")
    lines = [f'<Package id="notum.{dest_name}" name="Notum Dovvetech {title}">',
             '  <Requires package="notum.ndgui-lib" />',
             f'  <Provides role="{role}" />']
    lines += [f'  <{kind} src="{name}" />' for kind, name in scripts]
    lines.append("</Package>")
    open(os.path.join(ddir, "package.xml"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    return dest_name, creates


def main():
    for src, (role, title) in ROLES.items():
        name, n = fork(src, role, title)
        print(f"{name:28s} {role:24s} frames={n}")


if __name__ == "__main__":
    main()
