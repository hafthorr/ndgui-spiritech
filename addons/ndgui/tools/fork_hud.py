"""Fork the stock HUD/widget packages that are not plain core.window windows.

Run: python tools/fork_hud.py   (from the ndgui folder; then python tools/square_buttons.py)

Each stock package is copied to UI/Addons/ndgui-<slug>/ with a provider manifest for its
role, then restyled:
  * every XML gets the DarkTech text/tint palette (RECOLOR);
  * NCU / Target NCU vendor Core's ncu_view.lua as a package module whose Window uses the
    ndGUI frame (Core's shared module has no template option);
  * Faction vendors core.rollup, loading the ndGUI rollup frame from ndgui-lib;
  * Team Invite and the raid bars get ndGUI frame/plate art instead of stock borders.
Stops when a stock file no longer matches what the patch expects. Re-run after a client update.
"""
import os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ADDONS = os.path.normpath(os.path.join(HERE, "..", ".."))
STOCK = os.path.normpath(os.path.join(ADDONS, "..", "Packages"))
LIB = "library://notum.ndgui-lib/"
MARK = "-- ndGUI fork: generated by ndgui/tools/fork_hud.py from UI/Packages/{src}. Do not hand-edit.\n"

ROLES = {
    "Ncu": ("prk.ncu", "NCU"),
    "TargetNcu": ("prk.target-ncu", "Target NCU"),
    "Faction": ("prk.faction", "Faction"),
    "Chat": ("prk.chat", "Chat"),
    "ChatConfig": ("prk.chat-config", "Chat Config"),
    "RaidBar": ("prk.raid-bars", "Raid Bars"),
    "TimerBars": ("prk.timer-bars", "Timer Bars"),
    "TeamInvite": ("prk.team-invite", "Team Invite"),
    "SneakIndicator": ("prk.sneak-indicator", "Sneak Indicator"),
    "LogoutProgress": ("prk.logout-progress", "Logout Progress"),
}

# Stock colour -> DarkTech (theme.lua darktech). Applied to color=/tint=/hover_color= values.
RECOLOR = {
    "FFFFFF": "C5D7E6", "White": "C5D7E6", "0xFFFFFF": "C5D7E6",
    "FFFF88": "6CB6FF", "FFFF00": "6CB6FF", "0xE8C77C": "C6A24E",
    "0x8B9699": "3D6F9A", "0x8FB8CC": "7F9BB0", "0xB4C4C8": "7F9BB0",
    "0xFF0000": "D24B4B", "0xE05050": "D24B4B",
}
COLOR_ATTR = re.compile(r'\b(color|tint|hover_color)="([^"]*)"')

FRAME = f"""    <BitmapView image="{LIB}window/glass.png" />
    <BitmapView image="{LIB}window/titlebar.png" min_size="Point(1,27)" max_size="Point(-1,27)" v_alignment="top" />
    <BitmapView image="{LIB}window/edge_top.png" min_size="Point(1,3)" max_size="Point(-1,3)" v_alignment="top" />
    <BitmapView image="{LIB}window/edge_h.png" min_size="Point(1,3)" max_size="Point(-1,3)" v_alignment="bottom" />
    <BitmapView image="{LIB}window/edge_v.png" min_size="Point(3,1)" max_size="Point(3,-1)" h_alignment="left" />
    <BitmapView image="{LIB}window/edge_v_r.png" min_size="Point(3,1)" max_size="Point(3,-1)" h_alignment="right" />
    <BitmapView image="{LIB}window/corner_tl.png" min_size="Point(7,7)" max_size="Point(7,7)" h_alignment="left" v_alignment="top" layout_borders="Rect(3,3,0,0)" />
    <BitmapView image="{LIB}window/corner_br.png" min_size="Point(7,7)" max_size="Point(7,7)" h_alignment="right" v_alignment="bottom" layout_borders="Rect(0,0,3,3)" />
"""


def slug(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def must(text, old, new, what):
    if old not in text:
        raise SystemExit(f"{what}: stock text changed, expected {old[:70]!r}")
    return text.replace(old, new)


def recolor(xml):
    return COLOR_ATTR.sub(lambda m: f'{m.group(1)}="{RECOLOR.get(m.group(2), m.group(2))}"', xml)


# Live title updates also reach the docked page (ndgui-lib/lua/title.lua): Core writes the compact
# rollup_title only once. ui.text(ui.find(X, "window_title"), Y) -> Title.set(X, Y).
TITLE_FIND = re.compile(r'ui\.text\(ui\.find\(([^,()]+), "window_title"\), ')


def titles(code):
    return TITLE_FIND.sub(r'ui.require("notum.ndgui-lib/title").set(\1, ', code)


def vendor(ddir, core_file, old_define, new_define, patches, what):
    code = open(os.path.join(STOCK, "Core", core_file), encoding="utf-8").read()
    code = must(code, f'ui.define("{old_define}"', f'ui.define("{new_define}"', what)
    for old, new in patches:
        code = must(code, old, new, what)
    code = code.replace('ui.require("core.table")', 'ui.require("notum.ndgui-lib/table")')  # hideable columns (lib_table.py)
    code = titles(code)
    open(os.path.join(ddir, "ndgui_" + core_file), "w", encoding="utf-8", newline="\n").write(MARK.format(src="Core/" + core_file) + code)
    return "ndgui_" + core_file


def special(src, ddir):
    """Package-specific restyles. Returns extra module scripts to load before main.lua."""
    main = os.path.join(ddir, "main.lua")
    code = open(main, encoding="utf-8").read()
    extra = []
    if src in ("Ncu", "TargetNcu"):
        module = "ndgui." + slug(src).replace("-", "_") + "_view"
        extra.append(vendor(ddir, "ncu_view.lua", "ncu.view", module,
                            [("self.frame = Window.create({", f'self.frame = Window.create({{\n\t\t\ttemplate = "{LIB}window.xml",')], src))
        code = must(code, 'ui.require("ncu.view")', f'ui.require("{module}")', src)
    elif src == "Faction":
        extra.append(vendor(ddir, "rollup.lua", "core.rollup", "ndgui.rollup",
                            [('ui.shared_layout("rollup.xml")', f'ui.load("{LIB}rollup.xml")')], src))
        code = must(code, 'ui.require("core.rollup")', 'ui.require("ndgui.rollup")', src)
    elif src == "TeamInvite":
        path = os.path.join(ddir, "prompt.xml")
        xml = open(path, encoding="utf-8").read()
        xml = must(xml, '    <BorderView border_gfx="GFX_GUI_WINDOW3_BORDER" bg_gfx="GFX_GUI_WINDOW_BACKGROUND" />\n'
                        '    <BorderView border_gfx="GFX_GUI_TAB_BORDER" bg_gfx="GFX_GUI_TAB_BACKGROUND" layout_borders="Rect(4,26,4,4)" />\n',
                   FRAME, src)
        xml = must(xml, '<BorderView border_style="horizontal" border_gfx="GFX_GUI_TAB_ACTIVE" />',
                   f'<BitmapView image="{LIB}window/tab.png" />', src)
        xml = must(xml, 'image="gfx://GFX_GUI_WINDOW_ICON_I" graphic_mode="tinted"', 'image="gfx://GFX_GUI_WINDOW_ICON_I"', src)
        xml = must(xml, 'graphic_mode="tinted" alpha="0.6" active_alpha="0.85"', 'alpha="0.9" active_alpha="1"', src)
        xml = must(xml, '<TextView name="window_title" weight="1"', '<TextView name="window_title" weight="1" color="C5D7E6" font_size="13"', src)
        open(path, "w", encoding="utf-8", newline="\n").write(xml)
    elif src == "RaidBar":
        path = os.path.join(ddir, "window.xml")
        xml = open(path, encoding="utf-8").read()
        head = '<View name="raid_bar_window" capture_input="true" composite_layer="true" view_layout="horizontal" min_size="Point(176,34)" max_size="Point(176,34)">'
        xml = must(xml, head,
                   '<View name="raid_bar_window" capture_input="true" composite_layer="true" view_layout="stacked" min_size="Point(176,34)" max_size="Point(176,34)">\n'
                   f'    <BitmapView image="{LIB}chrome/plate.png" min_size="Point(176,34)" max_size="Point(176,34)" />\n'
                   '    <View view_layout="horizontal" min_size="Point(170,30)" max_size="Point(170,30)" layout_borders="Rect(3,2,0,0)">', src)
        xml = must(xml, "    </View>\n  </View>\n</root>", "    </View>\n    </View>\n  </View>\n</root>", src)
        open(path, "w", encoding="utf-8", newline="\n").write(xml)
    open(main, "w", encoding="utf-8", newline="\n").write(code)
    return extra


def fork(src, role, title):
    sdir = os.path.join(STOCK, src)
    dest = "ndgui-" + slug(src)
    ddir = os.path.join(ADDONS, dest)
    manifest = open(os.path.join(sdir, "package.xml"), encoding="utf-8").read()
    scripts = re.findall(r'<(Script|InteractionScript) src="([^"]+)"\s*/>', manifest)
    if os.path.isdir(ddir):
        shutil.rmtree(ddir)
    shutil.copytree(sdir, ddir)
    for fn in os.listdir(ddir):
        path = os.path.join(ddir, fn)
        if fn.endswith(".xml") and fn != "package.xml":
            xml = open(path, encoding="utf-8").read()
            open(path, "w", encoding="utf-8", newline="\n").write(recolor(xml))
    extra = special(src, ddir)
    for fn in os.listdir(ddir):
        if fn.endswith(".lua") and not fn.startswith("ndgui_"):
            path = os.path.join(ddir, fn)
            code = open(path, encoding="utf-8").read()
            code = code.replace('ui.require("core.table")', 'ui.require("notum.ndgui-lib/table")')  # hideable columns
            code = titles(code)
            open(path, "w", encoding="utf-8", newline="\n").write(MARK.format(src=src) + code)
    lines = [f'<Package id="notum.{dest}" name="Notum Dovvetech {title}">',
             '  <Requires package="notum.ndgui-lib" />',
             f'  <Provides role="{role}" />']
    lines += [f'  <Script src="{name}" />' for name in extra]
    lines += [f'  <{kind} src="{name}" />' for kind, name in scripts]
    lines.append("</Package>")
    open(os.path.join(ddir, "package.xml"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    return dest


def main():
    for src, (role, title) in ROLES.items():
        print(f"{fork(src, role, title):28s} {role}")


if __name__ == "__main__":
    main()
