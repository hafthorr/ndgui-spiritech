"""Build ndgui-lib/lua/table.lua: Core's table.lua with the column menu on every list.

Run from the ndgui folder:  python tools/lib_table.py
Since client 0.3 Core moves and hides columns itself (drag a header, or right-click it: the columns to
show + Move Left / Move Right; order and widths in <preference>.col_id / .col_width, hidden ones in
.col_hidden), but only for tables that pass column_menu (Inventory, bank, bags). This build turns that
on for every table, and carries over what older ndGUI saved: hidden ids as ",id,id," text (0.2.9 and
older) and the column order as <preference>.col_order (0.2.x). Every ndgui-* package that used
ui.require("core.table") is pointed at ui.require("notum.ndgui-lib/table") (fork_windows.py /
fork_hud.py do the same on regeneration). Re-run after a client update.
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ADDONS = os.path.normpath(os.path.join(HERE, "..", ".."))
CORE = os.path.normpath(os.path.join(ADDONS, "..", "Packages", "Core", "table.lua"))
OUT = os.path.join(ADDONS, "ndgui-lib", "lua", "table.lua")

OLD_REQ, NEW_REQ = 'ui.require("core.table")', 'ui.require("notum.ndgui-lib/table")'

MIGRATE = '''	-- ndGUI: settings saved by older ndGUI, rewritten once in the stock format
	local function ndgui_migrate(options)
		local key = options.preference or "listview_config"
		local function text(name)
			local ok, value = pcall(ui.preference.read, key .. name)
			return ok and type(value) == "string" and value or ""
		end
		-- hidden columns as ",id,id," text (ndGUI 0.2.9 and older)
		if not pcall(Preferences.read_array, key .. ".col_hidden", "text") then
			local ids = {}
			for id in text(".col_hidden"):gmatch("[^,]+") do
				ids[#ids + 1] = id
			end
			pcall(Preferences.write_array, key .. ".col_hidden", ids, "text")
		end
		-- column order as ",id,id," text (ndGUI 0.2.x) -> the stock col_id / col_width arrays
		local order = text(".col_order")
		if order ~= "" then
			local ok_ids, ids = pcall(Preferences.read_array, key .. ".col_id", "text")
			local ok_widths, widths = pcall(Preferences.read_array, key .. ".col_width", "float")
			local width_of = {}
			if ok_ids and ok_widths then
				for index, id in ipairs(ids) do
					width_of[id] = widths[index]
				end
			end
			local known, used, new_ids, new_widths = {}, {}, {}, {}
			for _, column in ipairs(options.columns) do
				known[column.id] = column
			end
			local function place(id)
				if known[id] and not used[id] then
					used[id] = true
					new_ids[#new_ids + 1] = id
					new_widths[#new_widths + 1] = width_of[id] or known[id].width
				end
			end
			for id in order:gmatch("[^,]+") do
				place(id)
			end
			for _, column in ipairs(options.columns) do
				place(column.id)
			end
			pcall(Preferences.write_array, key .. ".col_id", new_ids, "text")
			pcall(Preferences.write_array, key .. ".col_width", new_widths, "float")
			pcall(ui.preference.write, key .. ".col_order", "", "text")
		end
	end

	function Table.create(options)
		options.column_menu = options.column_menu ~= false -- ndGUI: the column menu on every list
		ndgui_migrate(options)
'''


def build():
    code = open(CORE, encoding="utf-8").read()
    m = re.match(r'\s*ui\.define\("core\.table", function\(\)\n(.*)\nend\)\s*$', code, re.S)
    if not m:
        raise SystemExit("Core/table.lua changed shape: no ui.define(\"core.table\", ...) wrapper")
    body = m.group(1)
    anchor = "\tfunction Table.create(options)\n"
    for needed in (anchor, "if options.column_menu then\n\t\t\tself:column_menu()", "function Table:restore_order(",
                   "function Table:move_column(", 'Preferences.read_array(self.preference .. ".col_hidden"'):
        if body.count(needed) != 1:
            raise SystemExit("Core/table.lua is not the shape this ndGUI expects (" + needed.strip().splitlines()[0] +
                             "). Update the game first; if it is up to date, this ndGUI needs an update.")
    body = body.replace(anchor, MIGRATE)
    head = ("-- ndGUI: generated by ndgui/tools/lib_table.py from UI/Packages/Core/table.lua. Do not hand-edit.\n"
            "-- Core's column menu (show / hide, Move Left / Right, drag a header) on every table.\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(head + body + "\n")


def repoint():
    n = 0
    for path in glob.glob(os.path.join(ADDONS, "ndgui-*", "*.lua")):
        code = open(path, encoding="utf-8").read()
        if OLD_REQ in code:
            open(path, "w", encoding="utf-8", newline="\n").write(code.replace(OLD_REQ, NEW_REQ))
            n += 1
    return n


if __name__ == "__main__":
    build()
    print(f"lib table written; {repoint()} packages repointed")
